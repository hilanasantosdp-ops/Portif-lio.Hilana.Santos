/* imagem que aparece com um leve fade quando termina de carregar */
function imagemComFade(src, alt, classeExtra) {
  const img = document.createElement("img");
  img.alt = alt;
  img.loading = "lazy";
  if (classeExtra) img.className = classeExtra;
  const caixa = document.createElement("div");
  caixa.className = "carregando";
  caixa.appendChild(img);
  let feito = false;
  const pronta = function () {
    if (feito) return;
    feito = true;
    caixa.classList.remove("carregando");
    img.classList.add("pronta");
  };
  img.addEventListener("load", pronta);
  img.addEventListener("error", pronta);
  img.src = src;
  if (img.complete) pronta();
  return { caixa: caixa, img: img };
}

function abrirProjeto(p, origem) {
  projetoAtual = p;
  imagensAtuais = listaImagens(p);
  gatilhoProjeto = origem;

  capaEl.innerHTML = "";
  capaEl.classList.remove("sem-imagem");
  if (imagensAtuais.length) {
    const capa = imagemComFade(imagensAtuais[0], p.titulo, "modal-capa-img");
    capaEl.appendChild(capa.caixa);
  } else {
    capaEl.classList.add("sem-imagem");
    capaEl.textContent = "Imagem do projeto";
  }

  modal.querySelector(".card-cat").textContent = p.categoria;
  modal.querySelector("h3").textContent = p.titulo;
  modal.querySelector(".desc").textContent = p.descricao;
  modal.querySelector(".aviso-exemplo").hidden = !p.exemplo;

  const dl = modal.querySelector("dl");
  dl.innerHTML = "";
  campos.forEach(function (c) {
    if (!p[c[1]]) return;
    const dt = document.createElement("dt");
    dt.textContent = c[0];
    const dd = document.createElement("dd");
    dd.textContent = p[c[1]];
    dl.appendChild(dt);
    dl.appendChild(dd);
  });

  const secaoGaleria = modal.querySelector(".modal-galeria-secao");
  grade.innerHTML = "";
  if (imagensAtuais.length > 1) {
    secaoGaleria.hidden = false;
    imagensAtuais.forEach(function (src, i) {
      const item = document.createElement("button");
      item.type = "button";
      item.className = "grade-item";
      item.setAttribute("aria-label", "Ver imagem " + (i + 1) + " de " + imagensAtuais.length);
      const foto = imagemComFade(src, p.titulo + " — imagem " + (i + 1));
      item.appendChild(foto.caixa);
      item.addEventListener("click", function () { abrirZoom(i, item); });
      grade.appendChild(item);
    });
  } else {
    secaoGaleria.hidden = true;
  }

  modal.querySelector(".modal-janela").scrollTop = 0;
  modal.classList.add("aberto");
  document.body.classList.add("modal-aberto");
  modal.querySelector(".modal-fechar").focus();
}

function fecharProjeto() {
  fecharZoom();
  modal.classList.remove("aberto");
  document.body.classList.remove("modal-aberto");
  if (gatilhoProjeto && document.contains(gatilhoProjeto)) gatilhoProjeto.focus();
}

function desenharZoom(direcao) {
  zoomPalco.innerHTML = "";
  const foto = imagemComFade(imagensAtuais[indice], projetoAtual.titulo + " — imagem " + (indice + 1) + " de " + imagensAtuais.length);
  if (direcao) foto.img.classList.add(direcao > 0 ? "vem-direita" : "vem-esquerda");
  zoomPalco.appendChild(foto.caixa);
  zoomCont.textContent = (indice + 1) + " / " + imagensAtuais.length;
  /* carrega a vizinha para a troca ficar rápida */
  if (imagensAtuais.length > 1) {
    new Image().src = imagensAtuais[(indice + 1) % imagensAtuais.length];
    new Image().src = imagensAtuais[(indice - 1 + imagensAtuais.length) % imagensAtuais.length];
  }
  const varias = imagensAtuais.length > 1;
  zoom.querySelector(".zoom-ant").hidden = !varias;
  zoom.querySelector(".zoom-prox").hidden = !varias;
}

function irParaZoom(n, direcao) {
  if (imagensAtuais.length < 2) return;
  indice = (n + imagensAtuais.length) % imagensAtuais.length;
  desenharZoom(direcao);
}

function abrirZoom(i, origem) {
  indice = i;
  gatilhoZoom = origem;
  desenharZoom();
  zoom.classList.add("aberto");
  document.body.classList.add("modal-aberto");
  zoom.querySelector(".zoom-fechar").focus();
}

function fecharZoom() {
  if (!zoom.classList.contains("aberto")) return;
  zoom.classList.remove("aberto");
  if (modal.classList.contains("aberto")) {
    document.body.classList.add("modal-aberto");
    if (gatilhoZoom && document.contains(gatilhoZoom)) gatilhoZoom.focus();
    else modal.querySelector(".modal-fechar").focus();
  } else {
    document.body.classList.remove("modal-aberto");
  }
}

modal.querySelector(".modal-fechar").addEventListener("click", fecharProjeto);
modal.addEventListener("click", function (e) { if (e.target === modal) fecharProjeto(); });
zoom.querySelector(".zoom-fechar").addEventListener("click", fecharZoom);
zoom.querySelector(".zoom-ant").addEventListener("click", function () { irParaZoom(indice - 1, -1); });
zoom.querySelector(".zoom-prox").addEventListener("click", function () { irParaZoom(indice + 1, 1); });

document.addEventListener("keydown", function (e) {
  if (zoom.classList.contains("aberto")) {
    if (e.key === "Escape") fecharZoom();
    else if (e.key === "ArrowLeft") irParaZoom(indice - 1, -1);
    else if (e.key === "ArrowRight") irParaZoom(indice + 1, 1);
    else if (e.key === "Tab") prenderFoco(zoom, e);
    return;
  }
  if (modal.classList.contains("aberto")) {
    if (e.key === "Escape") fecharProjeto();
    else if (e.key === "Tab") prenderFoco(modal, e);
  }
});

function prenderFoco(area, e) {
  const foco = Array.prototype.filter.call(
    area.querySelectorAll("button"),
    function (b) { return !b.hidden && b.offsetParent !== null; }
  );
  if (!foco.length) return;
  const primeiro = foco[0], ultimo = foco[foco.length - 1];
  if (e.shiftKey && document.activeElement === primeiro) { e.preventDefault(); ultimo.focus(); }
  else if (!e.shiftKey && document.activeElement === ultimo) { e.preventDefault(); primeiro.focus(); }
}

/* Deslizar o dedo no celular troca de imagem no visualizador */
(function ativarDeslizar() {
  let x0 = null;
  zoomPalco.addEventListener("touchstart", function (e) { x0 = e.touches[0].clientX; }, { passive: true });
  zoomPalco.addEventListener("touchend", function (e) {
    if (x0 === null) return;
    const dx = e.changedTouches[0].clientX - x0;
    x0 = null;
    if (Math.abs(dx) > 50) irParaZoom(dx < 0 ? indice + 1 : indice - 1, dx < 0 ? 1 : -1);
  }, { passive: true });
})();

